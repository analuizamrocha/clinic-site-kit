/**
 * Generate a client repository from this starter.
 *
 *   bun scripts/create-site.ts --brief <client.json> --out <dir> [--install] [--check]
 *
 * The brief is the site config as JSON (see ../../client.example.json), except
 * that the portrait is a local file: `practitioner.photo = { file, alt }`.
 * The script refuses to write anything if the brief fails validation, so a
 * half-filled brief never becomes a repository.
 */
import { spawnSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import sharp from 'sharp'
import { findSiteConfigProblems } from '../src/lib/site/validate'
import type { Practitioner, SiteConfig } from '../src/lib/site/types'
import { renderThemeCss } from '../src/lib/theme'

type BriefPractitioner = Omit<Practitioner, 'photo'> & { photo: { file: string; alt: string } }
export type ClientBrief = Omit<SiteConfig, 'fictional' | 'practitioner'> & {
  fictional?: boolean
  practitioner: BriefPractitioner
}

const STARTER = resolve(dirname(new URL(import.meta.url).pathname), '..')
/** Never copied into a client repo: build output, local tooling, the demo article. */
const SKIP = new Set(['node_modules', '.next', 'test-results', 'playwright-report', 'next-env.d.ts', 'tsconfig.tsbuildinfo', '.claude'])
const PORTRAIT_WIDTH = 900

const parseArgs = (argv: string[]) => {
  const args: Record<string, string | boolean> = {}
  for (let index = 0; index < argv.length; index += 1) {
    const key = argv[index]
    if (!key.startsWith('--')) continue
    const next = argv[index + 1]
    if (next && !next.startsWith('--')) {
      args[key.slice(2)] = next
      index += 1
    } else args[key.slice(2)] = true
  }
  return args
}

const fail = (message: string): never => {
  console.error(`\n✖ ${message}\n`)
  process.exit(1)
}

export class BriefError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'BriefError'
  }
}

/** Reads a brief from text. Throws BriefError before any file is written. */
export const parseBrief = (raw: string): ClientBrief => {
  let parsed: unknown
  try {
    parsed = JSON.parse(raw)
  } catch (error) {
    const detail = error instanceof Error ? error.message : 'parse error'
    throw new BriefError(`the brief is not valid JSON (${detail})`)
  }
  if (!parsed || typeof parsed !== 'object') throw new BriefError('the brief must be a JSON object')
  const brief = parsed as ClientBrief
  const photo = brief.practitioner?.photo
  if (typeof photo?.file !== 'string' || !photo.file.trim() || typeof photo?.alt !== 'string' || !photo.alt.trim()) {
    throw new BriefError('the brief is missing practitioner.photo.file or practitioner.photo.alt')
  }
  return brief
}

const run = (command: string, args: string[], cwd: string) => {
  console.log(`$ ${command} ${args.join(' ')}`)
  const result = spawnSync(command, args, { cwd, stdio: 'inherit' })
  if (result.status !== 0) fail(`${command} ${args.join(' ')} failed in ${cwd}`)
}

export const renderConfigFile = (config: SiteConfig) =>
  [
    "import type { SiteConfig } from '@/lib/site/types'",
    '',
    '/**',
    ' * Client facts. Generated by scripts/create-site.ts from the client brief;',
    ' * edit here from now on. `bun run theme` after changing the palette.',
    ' */',
    `const config: SiteConfig = ${JSON.stringify(config, null, 2)}`,
    '',
    'export default config',
    '',
  ].join('\n')

const main = async () => {
  const args = parseArgs(process.argv.slice(2))
  if (typeof args.brief !== 'string' || typeof args.out !== 'string') {
    fail('usage: bun scripts/create-site.ts --brief <client.json> --out <dir> [--install] [--check]')
  }
  const briefPath = resolve(String(args.brief))
  const out = resolve(String(args.out))
  if (out.startsWith(STARTER)) fail('refusing to generate inside the starter itself')
  if (existsSync(out) && readdirSync(out).length) fail(`${out} exists and is not empty`)

  let brief: ClientBrief
  try {
    brief = parseBrief(readFileSync(briefPath, 'utf8'))
  } catch (error) {
    if (error instanceof BriefError) fail(`${error.message}; nothing was written`)
    throw error
  }
  const photoFile = resolve(dirname(briefPath), brief.practitioner.photo.file)
  if (!existsSync(photoFile)) fail(`portrait not found: ${photoFile}`)

  // Portrait → webp at a sane width, with its real dimensions for next/image.
  const portrait = sharp(photoFile).rotate().resize({ width: PORTRAIT_WIDTH, withoutEnlargement: true }).webp({ quality: 82 })
  const { data: portraitData, info } = await portrait.toBuffer({ resolveWithObject: true })

  const config: SiteConfig = {
    ...brief,
    fictional: brief.fictional ?? false,
    practitioner: {
      ...brief.practitioner,
      photo: { src: '/images/practitioner.webp', alt: brief.practitioner.photo.alt, width: info.width, height: info.height },
    },
  }

  const problems = findSiteConfigProblems(config)
  if (problems.length) fail(`the brief has ${problems.length} problem(s); nothing was written:\n- ${problems.join('\n- ')}`)

  mkdirSync(out, { recursive: true })
  cpSync(STARTER, out, {
    recursive: true,
    filter: (source) => !relative(STARTER, source).split('/').some((part) => SKIP.has(part)),
  })

  writeFileSync(join(out, 'site', 'site.config.ts'), renderConfigFile(config))
  writeFileSync(join(out, 'src', 'app', 'theme.css'), renderThemeCss(config.brand.palette))
  writeFileSync(join(out, 'public', 'images', 'practitioner.webp'), portraitData)
  rmSync(join(out, 'public', 'images', 'practitioner.svg'), { force: true })
  rmSync(join(out, 'scripts', 'create-site.ts'), { force: true })
  // The generator test imports the script above. A client repo no longer has that script.
  rmSync(join(out, 'tests', 'unit', 'create-site.test.ts'), { force: true })

  // The demo article belongs to the demo practice; a client starts with an empty blog.
  const posts = join(out, 'content', 'posts')
  rmSync(posts, { recursive: true, force: true })
  mkdirSync(posts, { recursive: true })
  writeFileSync(join(posts, '.gitkeep'), '')

  const pkgPath = join(out, 'package.json')
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
  pkg.name = new URL(config.brand.url).hostname.replace(/^www\./, '').replace(/[^a-z0-9]+/g, '-')
  writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`)

  console.log(`\n✔ generated ${out}`)
  console.log(`  portrait ${info.width}×${info.height}, ${config.services.length} service(s), ${config.locations.length} location(s)`)

  if (args.install || args.check) {
    run('git', ['init', '-q'], out)
    run('bun', ['install'], out)
  }
  if (args.check) run('bun', ['run', 'check'], out)

  console.log(`
Next steps
  1. cd ${out}${args.install || args.check ? '' : ' && git init && bun install'}
  2. Fonts: src/app/fonts.ts · Extra blocked message terms: CLINICAL_TERMS
  3. Review every service text with the practitioner (indexable: false until approved)
  4. bun run check, then push and connect the repo to Vercel
`)
}

// Bun sets `import.meta.main` for the entry file. Importing this module from a test must not generate a site.
if ((import.meta as ImportMeta & { main?: boolean }).main) await main()
